// ── Merge ───────────────────────────────────────────────────────────────────
function mergeMissing(target, source) {
  let added = 0;
  for (const key of Object.keys(source)) {
    const sv = source[key];
    if (sv && typeof sv === "object" && !Array.isArray(sv)) {
      if (!target[key] || typeof target[key] !== "object") {
        target[key] = {};
      }
      added += mergeMissing(target[key], sv);
    } else {
      if (!(key in target)) {
        target[key] = sv;
        added++;
      }
    }
  }
  return added;
}

// Reorder keys in `obj` to match the order in `reference` (only top-level).
function alignTopLevelOrder(target, reference) {
  const ordered = {};
  for (const k of Object.keys(reference)) {
    if (k in target) ordered[k] = target[k];
  }
  for (const k of Object.keys(target)) {
    if (!(k in ordered)) ordered[k] = target[k];
  }
  return ordered;
}

