def merge_inplace(existing: OrderedDict, additions: dict) -> None:
    """Add new keys from `additions` into `existing` without overwriting."""
    for k, v in additions.items():
        if k in existing and isinstance(existing[k], dict) and isinstance(v, dict):
            merge_inplace(existing[k], v)
        elif k not in existing:
            existing[k] = v


def main() -> None:
    for locale, additions in T.items():
        path = MSG_DIR / f"{locale}.json"
        if not path.exists():
            print(f"  ✗ {path} — missing")
            continue
        with path.open("r", encoding="utf-8") as f:
            data = json.load(f, object_pairs_hook=OrderedDict)
        merge_inplace(data, additions)
        with path.open("w", encoding="utf-8") as f:
            json.dump(data, f, ensure_ascii=False, indent=2)
            f.write("\n")
        print(f"  ✓ {locale}.json")


if __name__ == "__main__":
    main()
